package io.adzubla.blocks.error;

/**
 * Values of the {@code code} property of error responses. Grouped as in the README's "Error responses" sections.
 */
public enum ErrorCode {

    // JSON request body errors (README §3.2)
    MALFORMED_JSON,
    UNKNOWN_JSON_FIELD,
    INVALID_ENUM_VALUE,
    INVALID_FIELD_VALUE,
    TYPE_MISMATCH,
    NULL_VALUE_NOT_ALLOWED,
    INVALID_TYPE_ID,
    INTEGER_OVERFLOW,
    MALFORMED_REQUEST_BODY,

    // Validation errors (README §3.3)
    VALIDATION_FAILED,

    // Data access errors (README §3.4)
    DUPLICATE_VALUE,
    REFERENTIAL_INTEGRITY_VIOLATION,
    DATA_INTEGRITY_VIOLATION,
    OPTIMISTIC_LOCKING_FAILURE,
    RESOURCE_NOT_FOUND,
    INVALID_PROPERTY_REFERENCE,

    // Spring MVC and unexpected errors (README §3.5)
    ROUTE_NOT_FOUND,
    METHOD_NOT_ALLOWED,
    UNSUPPORTED_MEDIA_TYPE,
    NOT_ACCEPTABLE,
    MISSING_REQUEST_PARAMETER,
    MISSING_REQUEST_PART,
    REQUEST_BINDING_ERROR,
    PARAMETER_TYPE_MISMATCH,
    PAYLOAD_TOO_LARGE,
    MALFORMED_MULTIPART_REQUEST,
    REQUEST_TIMEOUT,
    MISSING_PATH_VARIABLE,
    CONVERSION_NOT_SUPPORTED,
    MESSAGE_NOT_WRITABLE,
    METHOD_VALIDATION_ERROR, // only when the validation handler is disabled (README §6)
    ERROR_RESPONSE,
    INTERNAL_SERVER_ERROR
}
